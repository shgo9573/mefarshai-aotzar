ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) + '/'
F = '````'


def read(path):
    return open(ROOT + path, encoding='utf-8').read()


def grab(path, start, end='\n}\n'):
    src = read(path)
    i = src.index(start)
    j = src.index(end, i) + len(end) - 1
    return src[i:j].rstrip()


def code(text, lang='ts'):
    return f"{F}{lang}\n{text}\n{F}\n"


def fn(path, start, end='\n}\n'):
    return code(grab(path, start, end))


